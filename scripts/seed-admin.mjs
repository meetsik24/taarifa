import { randomBytes, scrypt } from "node:crypto";
import fs from "node:fs";
import { promisify } from "node:util";
import { Pool } from "pg";

const scryptAsync = promisify(scrypt);
const envPath = new URL("../.env", import.meta.url);

function ensureEnv(key, value) {
  const text = fs.readFileSync(envPath, "utf8");
  const match = text.match(new RegExp(`^${key}=(.*)$`, "m"));
  if (match) return match[1].trim();
  fs.appendFileSync(envPath, `${text.endsWith("\n") ? "" : "\n"}${key}=${value}\n`);
  return value;
}

const connectionString = process.env.DATABASE_URL?.trim();
if (!connectionString) {
  console.error("DATABASE_URL is missing.");
  process.exit(1);
}

const email = ensureEnv("ADMIN_EMAIL", "admin@wad2026.local");
const name = ensureEnv("ADMIN_NAME", "Msimamizi");
const password = ensureEnv("ADMIN_PASSWORD", `Wad-${randomBytes(9).toString("base64url")}`);
ensureEnv("AUTH_SECRET", randomBytes(32).toString("hex"));

const salt = randomBytes(16).toString("hex");
const hash = (await scryptAsync(password, salt, 64)).toString("hex");
const passwordHash = `scrypt$${salt}$${hash}`;

const pool = new Pool({ connectionString, max: 1 });
try {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS admins (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name text NOT NULL,
      email text NOT NULL UNIQUE,
      password_hash text NOT NULL,
      role text NOT NULL DEFAULT 'super_admin',
      created_at timestamptz NOT NULL DEFAULT now()
    )
  `);
  await pool.query("ALTER TABLE admins ADD COLUMN IF NOT EXISTS role text NOT NULL DEFAULT 'admin'");
  const existing = await pool.query("SELECT id FROM admins WHERE email = $1", [email.toLowerCase()]);
  if (existing.rowCount === 0) {
    await pool.query(
      "INSERT INTO admins (name, email, password_hash, role) VALUES ($1, $2, $3, 'super_admin')",
      [name, email.toLowerCase(), passwordHash],
    );
    console.log("CREATED");
  } else {
    console.log("EXISTS");
  }
  console.log(`LOGIN_EMAIL=${email}`);
  console.log(`LOGIN_PASSWORD=${password}`);
} finally {
  await pool.end();
}
