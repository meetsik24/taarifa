CREATE TABLE IF NOT EXISTS submissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL,
  tarehe text NOT NULL,
  kanda text NOT NULL,
  mkoa text NOT NULL,
  halmashauri text NOT NULL,
  shughuli text NOT NULL,
  aina text NOT NULL,
  eneo text NOT NULL DEFAULT '',
  mdau text NOT NULL DEFAULT '',
  hali text NOT NULL,
  vvu_me integer NOT NULL DEFAULT 0,
  vvu_ke integer NOT NULL DEFAULT 0,
  maambukizi_me integer NOT NULL DEFAULT 0,
  maambukizi_ke integer NOT NULL DEFAULT 0,
  waliounganishwa integer NOT NULL DEFAULT 0,
  elimu integer NOT NULL DEFAULT 0,
  kondomu integer NOT NULL DEFAULT 0,
  pep integer NOT NULL DEFAULT 0,
  jipime integer NOT NULL DEFAULT 0,
  ushahidi text NOT NULL DEFAULT '',
  sample boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS admins (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
