/** Stored report values stay in Swahili. This only changes how they are shown. */
export function translateTerm(locale: Locale, value: string): string {
  const parts = value.split("|").map((part) => part.trim()).filter(Boolean);
  if (parts.length > 1) {
    return parts.map((part) => (locale === "en" ? (TERM_EN[part] ?? part) : part)).join(", ");
  }
  if (locale !== "en") return value;
  return TERM_EN[value] ?? value;
}

/** Activity types as shown on a report, with the written "other" service when one was entered. */
export function describeActivities(locale: Locale, aina: string, other = ""): string {
  const shown = translateTerm(locale, aina);
  const note = other.trim();
  if (!note) return shown;
  const name = translateTerm(locale, "Huduma nyingine");
  if (shown.includes(name)) return shown.replace(name, `${name}: ${note}`);
  return `${shown}, ${name}: ${note}`;
}

