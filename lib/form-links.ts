import { randomBytes } from "node:crypto";
import { dbQuery } from "./db";

export type FormLink = {
  id: number;
  token: string;
  label: string;
  createdBy: string;
  createdAt: string;
  revokedAt: string | null;
};

type SqlRow = {
  id: number;
  token: string;
  label: string;
  created_by: string;
  created_at: Date | string;
  revoked_at: Date | string | null;
};

const CREATE_TABLE = `
  CREATE TABLE IF NOT EXISTS form_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token text NOT NULL UNIQUE,
    label text NOT NULL DEFAULT '',
    created_by text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    revoked_at timestamptz
  )
`;

let ready: Promise<void> | null = null;

function ensureTable(): Promise<void> {
  ready ??= dbQuery(CREATE_TABLE)
    .then(() => undefined)
    .catch((error: unknown) => {
      ready = null;
      throw error;
    });
  return ready;
}

function asIso(value: Date | string | null): string | null {
  if (value === null) return null;
  return value instanceof Date ? value.toISOString() : value;
}

function mapRow(row: SqlRow): FormLink {
  return {
    id: Number(row.id),
    token: row.token,
    label: row.label,
    createdBy: row.created_by,
    createdAt: asIso(row.created_at) ?? "",
    revokedAt: asIso(row.revoked_at),
  };
}

export function isFormToken(value: string): boolean {
  return /^[A-Za-z0-9_-]{16,64}$/.test(value);
}

export async function listFormLinks(): Promise<FormLink[]> {
  await ensureTable();
  const rows = await dbQuery<SqlRow>(
    `SELECT id, token, label, created_by, created_at, revoked_at
     FROM form_links
     ORDER BY id DESC`,
  );
  return rows.map(mapRow);
}

export async function insertFormLink(input: {
  label: string;
  createdBy: string;
}): Promise<FormLink> {
  await ensureTable();
  const rows = await dbQuery<SqlRow>(
    `INSERT INTO form_links (token, label, created_by)
     VALUES ($1, $2, $3)
     RETURNING id, token, label, created_by, created_at, revoked_at`,
    [randomBytes(18).toString("base64url"), input.label, input.createdBy],
  );
  return mapRow(rows[0]);
}

export async function revokeFormLink(id: number): Promise<void> {
  await ensureTable();
  await dbQuery(
    "UPDATE form_links SET revoked_at = now() WHERE id = $1 AND revoked_at IS NULL",
    [id],
  );
}

export async function findActiveFormLink(token: string): Promise<FormLink | null> {
  if (!isFormToken(token)) return null;
  await ensureTable();
  const rows = await dbQuery<SqlRow>(
    `SELECT id, token, label, created_by, created_at, revoked_at
     FROM form_links
     WHERE token = $1 AND revoked_at IS NULL`,
    [token],
  );
  return rows[0] ? mapRow(rows[0]) : null;
}
